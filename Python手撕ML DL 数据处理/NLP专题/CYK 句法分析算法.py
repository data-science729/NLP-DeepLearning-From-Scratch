"""
CYK（Cocke-Younger-Kasami）成分句法分析算法
难度：中等
分类：自然语言处理（NLP）/ 句法分析 / 区间动态规划（Interval DP）
教材出处：《自然语言处理》第 3 章 句法分析 3.2.1 节（基于上下文无关文法的成分句法分析）

【题目描述】
实现基于乔姆斯基范式（Chomsky Normal Form, CNF）的 CYK 成分句法分析算法。
CYK 是一种经典的自底向上（Bottom-up）句法分析算法，利用区间动态规划（Interval DP）思想，
根据给定的上下文无关文法规则，判断一个输入句子是否能被该文法所接受（即能否由起始符号 S 推导生成）。

【乔姆斯基范式（CNF）约束】
文法中的所有规则仅允许存在以下两种形式：
1. A -> w  （非终结符 -> 终结符/单个词，如 NP -> '他'，V -> '喜欢'）
2. A -> B C（非终结符 -> 两个非终结符，如 S -> NP VP，VP -> V V）

【算法流程与矩阵定义】
对于一个长度为 n 的词序列 words = [w1, w2, ..., wn]：
1. 构建一个大小为 (n + 1) * (n + 1) 的二维矩阵 T，其中每个单元格 T[i][j] 为一个集合（set），
   表示覆盖句子从词位置 i 到 j（即子切片 words[i:j]）的所有可能非终结符集合。
   （注：i 和 j 为词与词之间的间隔指针，0 <= i < j <= n）。
2. 初始化（区间跨度 d = 1）：
   遍历每个单词 wi（位置跨度为 [i-1, i]），根据文法中的终结符规则 A -> wi，
   将非终结符 A 放入 T[i-1][i] 集合中。
3. 区间动态规划填表（区间跨度 d 从 2 到 n）：
   - 外层循环：枚举区间跨度 d 从 2 到 n；
   - 中层循环：枚举左边界 i 从 0 到 n - d，右边界 j = i + d；
   - 内层切刀：在区间 [i, j] 中间枚举分割点 k（i + 1 <= k <= j - 1）；
   - 规则匹配：若文法中存在二元规则 A -> B C，且 B in T[i][k] 同时 C in T[k][j]，
     则将非终结符 A 加入到 T[i][j] 集合中。
4. 判定输出：
   若起始符号 S 包含在覆盖整句的矩阵格 T[0][n] 中，则说明该句子合法，返回 True；否则返回 False。

【教材示例推导（图 3.9）】
输入句子：["他", "喜欢", "跳", "芭蕾"]（n = 4）
文法规则：
  终结符规则：
    NP -> "他"
    V  -> "喜欢"
    V  -> "跳"
    N  -> "芭蕾"
  二元规则：
    S  -> NP VP
    VP -> V V
    VP -> VP N

推导过程：
- 第 1 层（长度 d=1）：
  T[0][1] = {NP} ("他")
  T[1][2] = {V}  ("喜欢")
  T[2][3] = {V}  ("跳")
  T[3][4] = {N}  ("芭蕾")

- 第 2 层（长度 d=2）：
  T[0][2] ("他喜欢"): k=1, T[0][1]={NP}, T[1][2]={V} -> 无匹配规则 -> set()
  T[1][3] ("喜欢跳"): k=2, T[1][2]={V}, T[2][3]={V} -> 命中 VP -> V V -> {VP}
  T[2][4] ("跳芭蕾"): k=3, T[2][3]={V}, T[3][4]={N} -> 无匹配规则 -> set()

- 第 3 层（长度 d=3）：
  T[0][3] ("他喜欢跳"): k=1 处 T[0][1]={NP}, T[1][3]={VP} -> 命中 S -> NP VP -> {S}
  T[1][4] ("喜欢跳芭蕾"): k=3 处 T[1][3]={VP}, T[3][4]={N} -> 命中 VP -> VP N -> {VP}

- 第 4 层（长度 d=4，整句）：
  T[0][4] ("他喜欢跳芭蕾"):
    k=1 处 T[0][1]={NP}, T[1][4]={VP} -> 命中 S -> NP VP -> {S}

最终判定：'S' in T[0][4] 为 True！
"""




