"""
ResNet BasicBlock / 最小残差块实现

背景说明：
    残差块是《Deep Residual Learning for Image Recognition》中提出的核心结构。
    在深层网络中，随着层数增加可能出现训练误差先降后升的网络退化问题（非过拟合，而是由于深层网络优化困难）。
    残差块通过显式拟合残差映射 F(x) = H(x) - x，将目标变换重写为：
        H(x) = F(x) + x
    当恒等映射为最优时，网络只需将残差项 F(x) 逼近于 0 即可；同时反向传播时加法节点提供了无阻碍的梯度通路
    (∂H/∂x = ∂F/∂x + 1)，从根本上缓解了深层网络的梯度消失问题。

题目描述：
    本题实现包含两层线性变换与后激活（Post-Activation）的最小残差块结构：
        residual_block(x, W1, W2) = ReLU(x + W2 @ ReLU(W1 @ x))

数学公式：
    y = ReLU(x + W2 @ ReLU(W1 @ x))
    其中：
        x ∈ R^d
        W1 ∈ R^{h×d}（本题约束方阵，即 h = d）
        W2 ∈ R^{d×h}（本题约束方阵，即 h = d）
        ReLU(z) = max(z, 0)，逐元素应用

参数说明：
    x: 输入向量，形状为 (d,) 或列表
    w1: 第一层线性变换权重矩阵 W1，形状为 (d, d)
    w2: 第二层线性变换权重矩阵 W2，形状为 (d, d)

返回值：
    与输入 x 同维度的向量，表示残差块的前向传播输出

评测判定：
    - 返回与输入同长的向量。
    - 浮点比较满足绝对误差 <= 1e-5 或相对误差 <= 1e-5 即判定通过。

示例 1:
    输入:
        x = [1, 2]
        w1 (2, 2) = [[1, 0], [0, 1]]
        w2 (2, 2) = [[0.5, 0], [0, 0.5]]
    输出:
        返回值 = [1.5, 3.0]

限制与约束条件：
    1. 维度约束：W1, W2 必须为方阵，且形状与 len(x) 一致（即 W_i ∈ R^{d×d}）。
    2. 无原地修改：禁止原地（in-place）修改输入 x、W1、W2。
    3. 激活函数：ReLU(z) = max(z, 0)，逐元素计算。
    4. 数据类型：x 的 dtype 至少为 float32（推荐 float64），返回值 dtype 保持与 x 一致。
    5. 无偏置项：线性变换不含偏置（bias = 0）。

边界情形：
    - W2 = 0（零矩阵）：残差项全为 0，输出退化为 y = ReLU(x)，捷径分支保证信息直通。
    - W1 = 0（零矩阵）：ReLU(0) = 0，同样输出退化为 y = ReLU(x)。
    - x 中存在负数：负数与主路径残差项相加，最终经外层 ReLU 处理，小于 0 的分量置为 0。
"""